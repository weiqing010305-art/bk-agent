import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const open = async name => {
  if (await page.locator('.menu-fab').isVisible()) await page.getByRole('button', { name: '打开导航' }).click();
  await page.locator('.side-item', { hasText: '概览' }).click();
  await page.locator('.icon-grid').getByRole('button', { name, exact: true }).click();
};
const bank = () => page.evaluate(() => JSON.parse(localStorage.getItem('qinghe-mock-v1')));
try {
  await page.goto(process.env.BASE_URL || 'http://127.0.0.1:5174', { waitUntil: 'networkidle' });
  await page.evaluate(() => { localStorage.clear(); sessionStorage.clear(); });
  await page.reload({ waitUntil: 'networkidle' });
  await open('交通卡');
  await page.getByLabel('交通卡号').fill('123456789012');
  await page.getByRole('button', { name: '50 元', exact: true }).click();
  await page.getByRole('button', { name: '下一步', exact: true }).click();
  await page.getByLabel('支付密码').fill('123456');
  await page.getByRole('button', { name: '确认支付', exact: true }).click();
  await page.getByText('支付成功', { exact: true }).waitFor();
  assert.equal((await bank()).transactions[0].name, '交通卡充值');
  await page.reload({ waitUntil: 'networkidle' }); await open('交通卡');
  assert.equal(await page.getByLabel('交通卡号').inputValue(), '123456789012');
  await open('储蓄计划');
  await page.getByLabel('目标名称').fill('旅行基金');
  await page.getByLabel('目标金额（元）').fill('1000');
  const d = new Date(); d.setDate(d.getDate() + 90);
  await page.getByLabel('目标日期').fill(d.toLocaleDateString('sv-SE'));
  await page.getByRole('button', { name: '保存目标', exact: true }).click();
  const before = (await bank()).balance;
  const move = async (direction, amount) => {
    await page.getByRole('button', { name: direction, exact: true }).click();
    await page.getByLabel('金额（元）', { exact: true }).fill(amount);
    await page.getByRole('button', { name: '下一步', exact: true }).click();
    await page.getByLabel('支付密码').fill('123456');
    await page.getByRole('button', { name: '确认划转', exact: true }).click();
    await page.getByText('资金划转成功', { exact: false }).waitFor();
  };
  await move('存入', '500');
  assert.equal((await bank()).balance, before - 50000);
  assert.equal(Object.values((await bank()).savings)[0], 50000);
  assert.equal(await page.getByRole('button', { name: '删除空计划' }).isDisabled(), true);
  await page.reload({ waitUntil: 'networkidle' }); await open('储蓄计划');
  await page.getByRole('heading', { name: '旅行基金' }).waitFor();
  await page.waitForTimeout(400);
  if (process.env.CAPTURE_SAVINGS) await page.screenshot({ path: 'savings-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.waitForTimeout(400);
  if (process.env.CAPTURE_SAVINGS) await page.screenshot({ path: 'savings-mobile.png', fullPage: true });
  await move('取回', '500');
  assert.equal((await bank()).balance, before);
  await page.getByRole('button', { name: '删除空计划' }).click();
  await page.getByText('还没有目标', { exact: false }).waitFor();
  assert.deepEqual(errors, []);
  console.log('交通卡记忆、充值记账、储蓄存取、刷新恢复及手机布局通过');
} finally { await browser.close(); }
