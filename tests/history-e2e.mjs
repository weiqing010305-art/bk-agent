import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const browser = await chromium.launch({ executablePath: process.env.BROWSER_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const baseURL = process.env.BASE_URL || 'http://127.0.0.1:5173';
await mkdir('artifacts', { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(baseURL);
  if (await page.locator('.backend-status').count()) await page.getByText('数据库演示已连接', { exact: false }).waitFor();
  const history = page.getByRole('region', { name: '历史对话' });
  const newChat = page.locator('.nav-new');
  await page.getByRole('button', { name: /智能转账 给朋友/ }).click();
  await page.getByRole('combobox').first().selectOption('zhang');
  await page.getByPlaceholder('0.00').fill('88.50');
  await page.getByLabel('输入消息').fill('稍后再转');
  await newChat.click();
  assert.equal(await history.locator('.history-select').count(), 2);
  assert.equal(await page.locator('.transfer-form').count(), 0);
  assert.equal(await page.getByLabel('输入消息').inputValue(), '');
  await newChat.click();
  assert.equal(await history.locator('.history-select').count(), 2);
  await page.getByRole('button', { name: /账单分析 看懂/ }).click();
  await history.locator('.history-select').filter({ hasText: '智能转账' }).click();
  assert.equal(await page.getByPlaceholder('0.00').inputValue(), '88.50');
  assert.equal(await page.getByLabel('输入消息').inputValue(), '稍后再转');
  await page.reload();
  if (await page.locator('.backend-status').count()) await page.getByText('数据库演示已连接', { exact: false }).waitFor();
  assert.equal(await history.locator('.history-select').count(), 2);
  assert.equal(await page.getByPlaceholder('0.00').inputValue(), '88.50');
  await page.getByRole('button', { name: '核对转账信息' }).click();
  await page.getByRole('dialog').waitFor();
  await page.keyboard.press('Control+k');
  assert.equal(await history.locator('.history-select').count(), 2);
  assert.equal(await newChat.isDisabled(), true);
  assert.equal(await page.locator('.history-delete').first().isDisabled(), true);
  await page.getByRole('dialog').getByRole('button', { name: '返回修改' }).click();
  await page.keyboard.press('Control+k');
  assert.equal(await history.locator('.history-select').count(), 3);
  await history.locator('.history-select').filter({ hasText: '账单分析' }).click();
  await page.getByText('九月资金流向').waitFor();
  await page.waitForTimeout(400);
  await page.screenshot({ path: 'artifacts/history-desktop.png' });
  // Same browser session, now verify history access at phone size.
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '打开菜单' }).click();
  await history.locator('.history-select').filter({ hasText: '智能转账' }).click();
  assert.equal(await page.getByPlaceholder('0.00').inputValue(), '88.50');
  assert.equal(await page.locator('.sidebar.open').count(), 0);
  await page.getByRole('button', { name: '打开菜单' }).click();
  await page.waitForTimeout(350);
  const sidebar = await page.locator('.sidebar.open').boundingBox();
  assert.ok(sidebar.x >= -1 && sidebar.x < 1 && sidebar.width <= 390);
  await page.screenshot({ path: 'artifacts/history-mobile.png' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);
  console.log('History passed: new/switch/reload, independent drafts, shortcut, confirmation guard and mobile navigation.');
} finally { await browser.close(); }
