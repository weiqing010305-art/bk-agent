import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const browser = await chromium.launch({ executablePath: process.env.BROWSER_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const baseURL = process.env.BASE_URL || 'http://127.0.0.1:5173';
await mkdir('artifacts', { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await page.goto(process.env.BASE_URL || 'http://127.0.0.1:5173');
  await page.getByText('数据库演示已连接', { exact: false }).waitFor();
  const before = await (await page.request.get(`${baseURL}/api/state`)).json();
  await page.getByRole('button', { name: /智能转账 给朋友/ }).click();
  await page.getByPlaceholder('0.00').fill('55');
  await page.locator('.nav-new').click();
  await page.getByRole('button', { name: /账单分析 看懂/ }).click();
  await page.getByRole('button', { name: '删除对话：智能转账', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '保留对话' }).click();
  assert.equal(await page.locator('.history-row').count(), 2);
  await page.getByRole('button', { name: '删除对话：智能转账', exact: true }).click();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(), 0);
  await page.getByRole('button', { name: '删除对话：智能转账', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '确认删除' }).click();
  assert.equal(await page.locator('.history-row').count(), 1);
  await page.getByText('九月资金流向').waitFor();
  await page.reload();
  await page.getByText('数据库演示已连接', { exact: false }).waitFor();
  assert.equal(await page.locator('.history-row').count(), 1);
  assert.equal(await page.getByRole('button', { name: '删除对话：智能转账', exact: true }).count(), 0);
  await page.locator('.nav-new').click();
  await page.getByRole('button', { name: /卡片管理 卡片状态/ }).click();
  await page.getByRole('button', { name: '删除对话：卡片管理', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '确认删除' }).click();
  await page.getByText('九月资金流向').waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '打开菜单' }).click();
  await page.getByRole('button', { name: '删除对话：账单分析', exact: true }).click();
  await page.getByRole('dialog').waitFor();
  await page.screenshot({ path: 'artifacts/delete-chat-mobile.png' });
  await page.getByRole('dialog').getByRole('button', { name: '确认删除' }).click();
  await page.getByText('今天想先处理什么？').waitFor();
  assert.equal(await page.locator('.history-row').count(), 1);
  assert.equal(await page.locator('.history-select').innerText().then(t => t.includes('新对话')), true);
  assert.deepEqual(await (await page.request.get(`${baseURL}/api/state`)).json(), before);
  await page.reload();
  await page.getByText('数据库演示已连接', { exact: false }).waitFor();
  await page.getByText('今天想先处理什么？').waitFor();
  console.log('Delete history passed: cancel, Escape, inactive/current/last delete, persistence, mobile and unchanged ledger.');
} finally { await browser.close(); }
