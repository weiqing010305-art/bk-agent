async function checkLayout(page) {
  await page.waitForTimeout(450);
  const layout = await page.evaluate(() => {
    const composer = document.querySelector('.composer').getBoundingClientRect();
    const conversation = document.querySelector('.conversation').getBoundingClientRect();
    const last = [...document.querySelectorAll('[data-message-id]')].at(-1).getBoundingClientRect();
    return { composerBottom: composer.bottom, conversationBottom: conversation.bottom, lastTop: last.top, height: innerHeight, bodyHeight: document.body.scrollHeight };
  });
  assert.ok(layout.composerBottom <= layout.height, JSON.stringify(layout));
  assert.ok(layout.lastTop < layout.conversationBottom, JSON.stringify(layout));
  assert.ok(layout.bodyHeight <= layout.height + 2, JSON.stringify(layout));
}
